-- Schema baseline for kafkatower-registry's own tables (PostgreSQL — production).
-- Numbered V3 (not V1) so it stays after kafkatower-common's V1/V2 in the one shared
-- flyway_schema_history — Flyway migrations from every module's classpath resources are
-- discovered and applied together against the single application database.

CREATE TABLE IF NOT EXISTS clusters (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL UNIQUE,
    json_data     TEXT         NOT NULL,
    last_modified TIMESTAMPTZ  NOT NULL
);

CREATE TABLE IF NOT EXISTS topic_access_controls (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_name     VARCHAR(255)  NOT NULL,
    cluster_name   VARCHAR(255)  NOT NULL,
    allowed_users  VARCHAR(4000),
    allowed_groups VARCHAR(4000),
    last_modified  TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uq_topic_cluster UNIQUE (topic_name, cluster_name)
);
